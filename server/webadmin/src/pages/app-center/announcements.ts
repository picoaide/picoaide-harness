/**
 * 面向员工的**公告模板**（2026-09-19 契约 §19 Q13「管理员运营:访问级别筛选 +
 * 面向员工的公告模板」；台账 UX-11）。
 *
 * 为什么模板要进代码而不是写在文档里：这次改造有**两个必须告知员工的变化**——
 *   ① 访问级别收敛：历史 `public`（匿名公开）退役，全部应用改为登录后使用；
 *   ② 形态变更：应用只在桌面客户端内打开（每个应用一个独立窗口），
 *      浏览器/公网不再有应用入口，分享只走深链。
 * 管理员最可能的处置是"忘了通知"，于是员工在浏览器里点旧地址打不开、以为系统坏了。
 * 把文案做成一键复制，是让"运营动作"（§19 Q13 的原话）真的能被执行。
 *
 * 纪律（改这些文案时必须保持）：
 *   - **不出现任何真实客户域名/主机名**（本仓公开）；需要位置的地方一律用
 *     `<…>` 占位符，由管理员替换。
 *   - 只写**产品行为**（入口在哪、地址会不会失效、分享怎么用、要不要重新登录），
 *     不写内部机制（迁移号、表名、scheme 常量、服务端实现）。
 *   - 访问级别口径只有两值（`login` / `whitelist`），历史值一律称
 *     「历史值 public（已退役）」—— 不写"公开"（那会让员工以为匿名还能用）。
 */

export interface AnnouncementTemplate {
  /** 稳定 id（测试与复制反馈用它，不用标题做键）。 */
  id: string
  /** 模板标题（管理员看的，不是公告正文）。 */
  title: string
  /** 收件对象（渲染成徽标）。 */
  audience: '员工' | '管理员'
  /** 一句话说明这个模板解决什么问题（为什么会有这次变更）。 */
  summary: string
  /** 公告正文（可直接复制；`<…>` 是待替换占位符）。 */
  body: string
}


-- 0079: 网关文件回收的**认领标记**（2026-09-22，审计 R7 N11）。
--
-- 背景：回收器原先"认领 = 直接删台账行，然后删上游对象"。若进程恰好死在两者之间
--   （重启/崩溃/被 kill），那个上游对象就**再无台账凭据**：既没有行让下一轮重试，
--   也没有任何记录说明它存在 —— 共享配额（每 key 25 GiB / 10000 文件）被静默泄漏。
--
-- 改成"标记认领、事后清行"：
--   1. 认领 = 在事务内锁行 + 复检仍过期 + `reaping_at = now()`（**保留行**）；
--   2. 删上游对象（404 视为成功）；
--   3. `DELETE … WHERE file_id = ? AND reaping_at IS NOT NULL` 收尾。
--   4. 崩在第 2/3 步之间 ⇒ 行还在、标记还在 ⇒ 下一轮（标记租约过期后）重新认领，
--      再删一次上游（已是 404 ⇒ 成功）→ 收尾删行。**不会再产生孤儿对象**。
--
-- 租约语义：`reaping_at` 早于 10 分钟的行可以被重新认领（认领方崩溃后的自愈窗口，
--   比回收间隔 5 分钟略长，避免正常在跑的批次被下一轮抢走）。
-- 重新登记（上传把过期行转手）会清空 `reaping_at`（见 RecordGatewayFileSize），
--   因此"标记还在"就是"这份认领仍然有效"的判据 —— 续期后回收器会放弃删上游对象。
ALTER TABLE gateway_files ADD COLUMN IF NOT EXISTS reaping_at TIMESTAMPTZ;

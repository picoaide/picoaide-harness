-- 0081: 网关文件回收的**世代号**（fencing token，2026-09-23 审计 R4-C-1）。
--
-- 背景（缺陷形态）：回收器在「复检认领」与「上游 DELETE 返回」之间不是原子边界。
--   上游 DELETE 是一次不受本地事务约束的外部副作用，而复检通过之后到 DELETE 生效
--   之前存在窗口：若同一个 `file_id`（上游按内容去重会把同一个 id 发给第二个上传者）
--   在这段窗口里被**重新登记**，过期行的转手（RecordGatewayFileSize 按设计允许过期
--   行转手并清空 reaping_at）会成功 —— 回收器随后把**新上传者的上游对象**删掉，而
--   本地台账仍显示"该文件有效、属于第二个上传者"。后果：第二个上传者之后引用该
--   file_id 的聊天全部拿到上游 404，且本地没有任何一条日志把这归因到回收器。
--
-- 修法 = 把"删除权"收敛成一个**不会被转手的新一代夺取**的令牌：
--   1. `reap_gen` 是行的世代号：认领时 +1，重新登记（转手/续期）时也 +1；
--   2. 回收器认领后拿到 `(file_id, reap_gen)`，DELETE **之前**校验"世代未变且认领
--      仍在租约内"，**返回之后**再校验一次（收尾的 DELETE 也带世代谓词）；
--   3. 认领在租约内时，登记路径**拒绝转手**（RecordGatewayFileSize 的 ON CONFLICT
--      WHERE 增加租约判据，0 行 ⇒ 返回 ErrGatewayFileReapClaimed，由上传路径放弃
--      这个 id）—— 两个写者对同一个 id 不可能同时成立；
--   4. 世代变了就放弃删除（行保持在**新一代**手里），并把 file_id + 世代写进日志。
--
-- 为什么用"世代号"而不是加时间戳比较：世代是单调的**令牌**，不依赖时钟；多实例
-- 并发认领时后者的世代必然更大，前者无论何时发起 DELETE 都会在前后两次校验里发现
-- 自己已被取代（Kleppmann 的 fencing token 语义）。
ALTER TABLE gateway_files ADD COLUMN IF NOT EXISTS reap_gen BIGINT NOT NULL DEFAULT 0;
